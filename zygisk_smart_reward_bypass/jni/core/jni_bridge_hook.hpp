#pragma once

#include <jni.h>
#include <cstddef>

namespace smartreward {

// ---------------------------------------------------------------------------
// Перехват границы «нативный код -> Java» для игр на нативных движках
// (Cocos2d-x, LÖVE 2D, Unreal и прочие, где нет C#-слоя).
//
// В таких играх рекламная логика находится в Java, а игровой код на C++
// обращается к ней через JNI. Собственного C#-кода нет, поэтому перехват
// IL2CPP к ним неприменим.
//
// Механизм: таблица функций JNI (JNINativeInterface) — это обычный массив
// указателей. Достаточно подменить в нём несколько записей, чтобы видеть и
// изменять каждый вызов Java-метода из нативного кода. Ни инлайн-перехвата,
// ни фреймворков перехвата методов ART для этого не требуется.
//
// Перехватываются только вызовы, возвращающие boolean (проверки готовности)
// и void (показ). Всё остальное проходит без изменений.
// ---------------------------------------------------------------------------

// Устанавливает перехват. Безопасно вызывать повторно: установка выполняется
// один раз на процесс.
bool install_jni_bridge_hook(JNIEnv *env, const char *package_name);

// Сводка активности: сколько методов распознано и сколько раз сработал перехват.
void log_jni_bridge_activity(bool force);

} // namespace smartreward
